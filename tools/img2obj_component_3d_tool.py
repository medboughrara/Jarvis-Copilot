@dataclass
class MeshBuilder:
    """Helper to construct 3D vertices, normals, and quad/triangle faces."""
    vertices: List[Tuple[float, float, float]] = field(default_factory=list)
    normals: List[Tuple[float, float, float]] = field(default_factory=list)
    faces: List[Tuple[List[int], str]] = field(default_factory=list)  # (vertex_indices_1_based, material_name)

    def add_vertex(self, x: float, y: float, z: float) -> int:
        self.vertices.append((round(x, 4), round(y, 4), round(z, 4)))
        return len(self.vertices)

    def add_box(
        self,
        cx: float, cy: float, cz: float,
        dx: float, dy: float, dz: float,
        material: str = "Body_Black_Epoxy"
    ) -> None:
        """Adds an axis-aligned 3D box centered at (cx, cy, cz) with size (dx, dy, dz)."""
        hx, hy, hz = dx / 2.0, dy / 2.0, dz / 2.0
        
        # 8 corners
        v1 = self.add_vertex(cx - hx, cy - hy, cz - hz)
        v2 = self.add_vertex(cx + hx, cy - hy, cz - hz)
        v3 = self.add_vertex(cx + hx, cy + hy, cz - hz)
        v4 = self.add_vertex(cx - hx, cy + hy, cz - hz)
        v5 = self.add_vertex(cx - hx, cy - hy, cz + hz)
        v6 = self.add_vertex(cx + hx, cy - hy, cz + hz)
        v7 = self.add_vertex(cx + hx, cy + hy, cz + hz)
        v8 = self.add_vertex(cx - hx, cy + hy, cz + hz)

        # 6 faces (quads with CCW winding)
        # Bottom (Z-)
        self.faces.append(([v1, v2, v3, v4], material))
        # Top (Z+)
        self.faces.append(([v5, v8, v7, v6], material))
        # Front (Y-)
        self.faces.append(([v1, v5, v6, v2], material))
        # Back (Y+)
        self.faces.append(([v3, v7, v8, v4], material))
        # Left (X-)
        self.faces.append(([v4, v8, v5, v1], material))
        # Right (X+)
        self.faces.append(([v2, v6, v7, v3], material))

    def add_cylinder(
        self,
        cx: float, cy: float, cz: float,
        radius: float, height: float,
        segments: int = 12,
        material: str = "Leads_Matte_Tin"
    ) -> None:
        """Adds a vertical cylinder along Z axis."""
        hz = height / 2.0
        bot_center = self.add_vertex(cx, cy, cz - hz)
        top_center = self.add_vertex(cx, cy, cz + hz)
        
        bot_rim = []
        top_rim = []
        for i in range(segments):
            angle = 2.0 * math.pi * i / segments
            x = cx + radius * math.cos(angle)
            y = cy + radius * math.sin(angle)
            bot_rim.append(self.add_vertex(x, y, cz - hz))
            top_rim.append(self.add_vertex(x, y, cz + hz))

        # Side quads & Top/Bottom caps
        for i in range(segments):
            nxt = (i + 1) % segments
            # Side
            self.faces.append(([bot_rim[i], top_rim[i], top_rim[nxt], bot_rim[nxt]], material))
            # Bottom cap
            self.faces.append(([bot_center, bot_rim[nxt], bot_rim[i]], material))
            # Top cap
            self.faces.append(([top_center, top_rim[i], top_rim[nxt]], material))

    def to_obj_string(self, mtl_filename: str = "materials.mtl") -> str:
        """Serializes mesh into standard Wavefront .OBJ format."""
        lines = [
            f"# Generated by Jarvis img2obj 3D Electronic Component Engine",
            f"mtllib {mtl_filename}\n"
        ]
        for v in self.vertices:
            lines.append(f"v {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}")
        
        current_mat = None
        for face_verts, mat in self.faces:
            if mat != current_mat:
                lines.append(f"usemtl {mat}")
                current_mat = mat
            f_str = " ".join(str(idx) for idx in face_verts)
            lines.append(f"f {f_str}")
            
        return "\n".join(lines)


