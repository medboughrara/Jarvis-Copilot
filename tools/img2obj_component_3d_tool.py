@tool
def generate_3d_part_from_image_or_spec(
    package_or_image: str,
    output_name: str = "component_3d",
    output_dir: str = "models_3d",
    dimensions: Optional[Dict[str, float]] = None
) -> dict:
    """
    Generates Wavefront .OBJ/.MTL and procedural Three.js 3D models from a package name (e.g. SOT-223, 0805, QFP-48, USB-C)
    or reference image/datasheet diagram using procedural code reconstruction.

    Args:
        package_or_image: Standard package name (e.g. '0805', 'SOT-223', 'SOIC-8', 'QFP-48', 'TO-220', 'USB-C')
                          or file path to a 2D component diagram / datasheet image.
        output_name: Base filename for output models (without extension).
        output_dir: Output directory to save .obj and .mtl files.
        dimensions: Optional dict overriding physical dimensions in mm (e.g. {'length': 2.0, 'width': 1.25}).

    Returns:
        dict with paths to generated .obj, .mtl, Three.js factory, and vertex/face metrics.
    """
    pkg_key = package_or_image.upper().strip()
    dims = dimensions or {}
    
    logger.info(f"[img2obj] Generating 3D component model for '{pkg_key}' into '{output_dir}'")
    
    # 1. Match package builder
    builder_fn = None
    for key, fn in PACKAGE_BUILDERS.items():
        if key in pkg_key:
            builder_fn = fn
            break
            
    if not builder_fn:
        # Default fallback to IC body
        builder_fn = _build_soic8
        
    mb = builder_fn(dims)
    
    os.makedirs(output_dir, exist_ok=True)
    obj_path = os.path.join(output_dir, f"{output_name}.obj")
    mtl_path = os.path.join(output_dir, f"{output_name}.mtl")
    threejs_path = os.path.join(output_dir, f"{output_name}_three.js")
    
    # Write .mtl
    with open(mtl_path, "w", encoding="utf-8") as f:
        f.write(MATERIALS_MTL)
        
    # Write .obj
    obj_content = mb.to_obj_string(os.path.basename(mtl_path))
    with open(obj_path, "w", encoding="utf-8") as f:
        f.write(obj_content)
        
    # Write Three.js Factory
    threejs_code = _generate_threejs_factory(pkg_key, dims)
    with open(threejs_path, "w", encoding="utf-8") as f:
        f.write(threejs_code)
        
    return {
        "status": "success",
        "summary": f"Generated 3D Model for '{pkg_key}' ({len(mb.vertices)} vertices, {len(mb.faces)} faces).",
        "data": {
            "package": pkg_key,
            "obj_path": os.path.abspath(obj_path),
            "mtl_path": os.path.abspath(mtl_path),
            "threejs_path": os.path.abspath(threejs_path),
            "vertices_count": len(mb.vertices),
            "faces_count": len(mb.faces)
        }
    }


@tool
def attach_3d_model_to_kicad_footprint(
    pcb_file_path: str,
    reference_designator: str,
    model_obj_path: str,
    offset_xyz: Optional[List[float]] = None,
    scale_xyz: Optional[List[float]] = None,
    rotate_xyz: Optional[List[float]] = None
) -> dict:
    """
    Injects a 3D .OBJ / .STEP model reference into a footprint inside a KiCad .kicad_pcb layout file.

    Args:
        pcb_file_path: Absolute path to the target .kicad_pcb board file.
        reference_designator: Component reference designator (e.g. 'U1', 'C1', 'R2', 'J1').
        model_obj_path: Relative or absolute path to the .obj/.step 3D model.
        offset_xyz: Optional (X, Y, Z) offset in mm [default: 0, 0, 0].
        scale_xyz: Optional (X, Y, Z) scale factor [default: 1, 1, 1].
        rotate_xyz: Optional (X, Y, Z) rotation in degrees [default: 0, 0, 0].

    Returns:
        dict with status and confirmation of attached 3D model in KiCad PCB.
    """
    if not os.path.exists(pcb_file_path):
        return {
            "status": "error",
            "summary": f"KiCad PCB file not found: {pcb_file_path}",
            "data": {}
        }
        
    off = offset_xyz or [0.0, 0.0, 0.0]
    sc = scale_xyz or [1.0, 1.0, 1.0]
    rot = rotate_xyz or [0.0, 0.0, 0.0]
    
    norm_model_path = model_obj_path.replace("\\", "/")
    model_s_expr = f"""    (model "{norm_model_path}"
      (offset (xyz {off[0]} {off[1]} {off[2]}))
      (scale (xyz {sc[0]} {sc[1]} {sc[2]}))
      (rotate (xyz {rot[0]} {rot[1]} {rot[2]}))
    )"""

    with open(pcb_file_path, "r", encoding="utf-8") as f:
        content = f.read()

    # Locate the target footprint block
    footprint_pattern = f'(fp_text reference "{reference_designator}"'
    if footprint_pattern not in content:
        # Fallback to alternate reference pattern
        footprint_pattern = f'(property "Reference" "{reference_designator}"'
        
    if footprint_pattern in content:
        # Inject model before footprint closing parenthesis
        idx = content.find(footprint_pattern)
        # Find enclosing footprint closing paren
        fp_end = content.find("\n  )", idx)
        if fp_end != -1:
            updated_content = content[:fp_end] + "\n" + model_s_expr + content[fp_end:]
            with open(pcb_file_path, "w", encoding="utf-8") as f:
                f.write(updated_content)
                
            return {
                "status": "success",
                "summary": f"Attached 3D model '{os.path.basename(model_obj_path)}' to {reference_designator} in KiCad PCB.",
                "data": {
                    "pcb_file": pcb_file_path,
                    "reference": reference_designator,
                    "model_path": norm_model_path
                }
            }

    return {
        "status": "warning",
        "summary": f"Footprint '{reference_designator}' reference not found in PCB file.",
        "data": {"pcb_file": pcb_file_path}
    }


@tool
def preview_3d_component_threejs(
    package_name: str
) -> dict:
    """
    Returns browser-ready Three.js JavaScript source code for rendering interactive 3D component visualization in WebGL.

    Args:
        package_name: Component package type (e.g. 'SOT-223', 'QFP-48', '0805', 'USB-C').

    Returns:
        dict containing executable Three.js JavaScript factory code.
    """
    code = _generate_threejs_factory(package_name, {})
    return {
        "status": "success",
        "summary": f"Generated Three.js WebGL visualization factory for {package_name}.",
        "data": {
            "package": package_name,
            "threejs_source": code
        }
    }
