def _generate_threejs_factory(package_name: str, dimensions: Dict[str, Any]) -> str:
    """Generates pure client-side Three.js code to procedurally construct the 3D part."""
    code = f"""// 3D Procedural Three.js Factory for {package_name}
// Generated by Jarvis img2obj Engine
export function createPartMesh(THREE) {{
    const group = new THREE.Group();
    group.name = "{package_name}_Component";

    // PBR Materials
    const blackEpoxy = new THREE.MeshStandardMaterial({{
        color: 0x141416,
        roughness: 0.85,
        metalness: 0.05
    }});
    const matteTin = new THREE.MeshStandardMaterial({{
        color: 0xc8c8cc,
        roughness: 0.35,
        metalness: 0.85
    }});
    const metalTab = new THREE.MeshStandardMaterial({{
        color: 0xd0d2d6,
        roughness: 0.25,
        metalness: 0.95
    }});
    const pinGold = new THREE.MeshStandardMaterial({{
        color: 0xdfb830,
        roughness: 0.20,
        metalness: 0.90
    }});

    // Procedural Geometry Assembly
    const bodyGeom = new THREE.BoxGeometry(
        {dimensions.get('length', 4.0)},
        {dimensions.get('width', 3.0)},
        {dimensions.get('height', 1.2)}
    );
    const bodyMesh = new THREE.Mesh(bodyGeom, blackEpoxy);
    bodyMesh.position.z = {dimensions.get('height', 1.2) / 2.0};
    group.add(bodyMesh);

    // Return root 3D anchor
    return group;
}}
"""
    return code


