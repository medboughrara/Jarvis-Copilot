def _build_smd_passive_0805(dimensions: Dict[str, float]) -> MeshBuilder:
    """Builds an SMD Passive chip component (e.g. 0805 / 0603 / 0402 Resistor or Capacitor)."""
    mb = MeshBuilder()
    length = dimensions.get("length", 2.0)    # X
    width = dimensions.get("width", 1.25)     # Y
    height = dimensions.get("height", 0.9)    # Z
    cap_len = dimensions.get("cap_len", 0.4)
    is_cap = dimensions.get("is_capacitor", True)
    
    body_mat = "Ceramic_Brown" if is_cap else "Body_Black_Epoxy"
    center_len = length - (2.0 * cap_len)
    
    # 1. Main dielectric/resistive central body
    mb.add_box(0, 0, height / 2.0, center_len, width, height, material=body_mat)
    
    # 2. Left and Right metallic termination caps
    x_left = - (length / 2.0) + (cap_len / 2.0)
    x_right = (length / 2.0) - (cap_len / 2.0)
    mb.add_box(x_left, 0, height / 2.0, cap_len, width, height, material="Leads_Matte_Tin")
    mb.add_box(x_right, 0, height / 2.0, cap_len, width, height, material="Leads_Matte_Tin")
    
    return mb


def _build_sot223(dimensions: Dict[str, float]) -> MeshBuilder:
    """Builds a SOT-223 Voltage Regulator / Power Transistor (e.g. AMS1117)."""
    mb = MeshBuilder()
    body_l = dimensions.get("body_length", 6.5)  # X
    body_w = dimensions.get("body_width", 3.5)   # Y
    body_h = dimensions.get("body_height", 1.6)  # Z
    
    # 1. Molded Plastic Body
    mb.add_box(0, 0, body_h / 2.0, body_l, body_w, body_h, material="Body_Black_Epoxy")
    
    # 2. Pin 1 orientation notch / index dot
    mb.add_box(-2.4, -1.0, body_h + 0.02, 0.4, 0.4, 0.04, material="White_Marking")
    
    # 3. Three Bottom Leads (Pins 1, 2, 3)
    lead_w = 0.7
    lead_pitch = 2.3
    lead_extend = 1.6
    for i, x_pos in enumerate([-lead_pitch, 0.0, lead_pitch]):
        mb.add_box(x_pos, -(body_w / 2.0 + lead_extend / 2.0), 0.2, lead_w, lead_extend, 0.3, material="Leads_Matte_Tin")
    
    # 4. Top Large Thermal Heatsink Tab (Pin 4)
    tab_w = 3.0
    mb.add_box(0.0, (body_w / 2.0 + lead_extend / 2.0), 0.2, tab_w, lead_extend, 0.3, material="Metal_Tab")
    
    return mb


def _build_soic8(dimensions: Dict[str, float]) -> MeshBuilder:
    """Builds a SOIC-8 / SOP-8 Dual-In-Line SMD IC Package."""
    mb = MeshBuilder()
    body_l = dimensions.get("body_length", 4.9)  # X
    body_w = dimensions.get("body_width", 3.9)   # Y
    body_h = dimensions.get("body_height", 1.5)  # Z
    pins_per_side = 4
    pitch = 1.27
    lead_w = 0.45
    lead_ext = 1.0
    
    # 1. Main Molded Body
    mb.add_box(0, 0, body_h / 2.0, body_l, body_w, body_h, material="Body_Black_Epoxy")
    
    # 2. Pin 1 Index Chamfer
    mb.add_box(-1.8, -1.2, body_h + 0.02, 0.5, 0.5, 0.04, material="White_Marking")
    
    # 3. Dual side gull-wing leads
    start_x = - ((pins_per_side - 1) * pitch) / 2.0
    for i in range(pins_per_side):
        x = start_x + (i * pitch)
        # Bottom side pins (1-4)
        mb.add_box(x, -(body_w / 2.0 + lead_ext / 2.0), 0.15, lead_w, lead_ext, 0.25, material="Leads_Matte_Tin")
        # Top side pins (5-8)
        mb.add_box(x, (body_w / 2.0 + lead_ext / 2.0), 0.15, lead_w, lead_ext, 0.25, material="Leads_Matte_Tin")
        
    return mb


def _build_qfp48(dimensions: Dict[str, float]) -> MeshBuilder:
    """Builds a QFP-48 / TQFP-48 / QFN-32 Quad Flat Package IC."""
    mb = MeshBuilder()
    body_size = dimensions.get("body_size", 7.0)  # X & Y
    body_h = dimensions.get("body_height", 1.0)
    pins_per_side = 12
    pitch = 0.5
    lead_w = 0.22
    lead_ext = 0.8
    
    # 1. Main Plastic Body
    mb.add_box(0, 0, body_h / 2.0, body_size, body_size, body_h, material="Body_Black_Epoxy")
    
    # 2. Pin 1 Index Dot
    mb.add_box(- (body_size / 2.0 - 0.8), - (body_size / 2.0 - 0.8), body_h + 0.02, 0.6, 0.6, 0.04, material="White_Marking")
    
    # 3. 4-Sided Perimeter Leads
    start_offset = - ((pins_per_side - 1) * pitch) / 2.0
    for i in range(pins_per_side):
        pos = start_offset + (i * pitch)
        # South
        mb.add_box(pos, - (body_size / 2.0 + lead_ext / 2.0), 0.1, lead_w, lead_ext, 0.18, material="Leads_Matte_Tin")
        # North
        mb.add_box(pos, (body_size / 2.0 + lead_ext / 2.0), 0.1, lead_w, lead_ext, 0.18, material="Leads_Matte_Tin")
        # West
        mb.add_box(- (body_size / 2.0 + lead_ext / 2.0), pos, 0.1, lead_ext, lead_w, 0.18, material="Leads_Matte_Tin")
        # East
        mb.add_box((body_size / 2.0 + lead_ext / 2.0), pos, 0.1, lead_ext, lead_w, 0.18, material="Leads_Matte_Tin")
        
    return mb


def _build_to220(dimensions: Dict[str, float]) -> MeshBuilder:
    """Builds a TO-220 Through-Hole Power Transistor / Regulator package."""
    mb = MeshBuilder()
    body_w = 10.0
    body_d = 4.5
    body_h = 9.0
    tab_h = 6.0
    tab_thick = 1.3
    
    # 1. Molded Plastic Lower Body
    mb.add_box(0, 0, body_h / 2.0 + 3.0, body_w, body_d, body_h, material="Body_Black_Epoxy")
    
    # 2. Upper Metal Mounting Tab
    mb.add_box(0, (body_d - tab_thick) / 2.0, body_h + tab_h / 2.0 + 3.0, body_w, tab_thick, tab_h, material="Metal_Tab")
    
    # 3. Three Through-hole Pins extending downwards
    for x_pos in [-2.54, 0.0, 2.54]:
        mb.add_box(x_pos, 0, 1.5, 0.8, 0.8, 7.0, material="Leads_Matte_Tin")
        
    return mb


def _build_usb_c(dimensions: Dict[str, float]) -> MeshBuilder:
    """Builds a USB Type-C Receptacle 16/24-pin Connector."""
    mb = MeshBuilder()
    shell_w = 8.94
    shell_d = 7.35
    shell_h = 3.26
    
    # Outer Metallic Shielding Shell
    mb.add_box(0, 0, shell_h / 2.0, shell_w, shell_d, shell_h, material="Metal_Tab")
    # Internal Black Tongue
    mb.add_box(0, -0.5, shell_h / 2.0, shell_w - 1.8, shell_d - 1.2, 0.65, material="Body_Black_Epoxy")
    # Golden Contacts
    mb.add_box(0, -1.0, shell_h / 2.0, shell_w - 2.5, 2.0, 0.75, material="Pin_Gold")
    
    return mb


